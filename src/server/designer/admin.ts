import 'server-only';

import { randomBytes } from 'node:crypto';
import { chmodSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import type { Db } from '../db/client';
import { seedAdmin } from '../seed/admin';
import { findUserByEmail } from '../users/repo';

// The designer admin (capability designer-mode; spec/data.md → Seed data): `designer@blog0.local`
// with a generated password, created once by `pnpm dev:design`. The password is returned ONLY
// when it was just generated (the caller prints it once) and is kept in var/designer-admin.txt
// (mode 0600) so the designer can look it up later. `--reset-designer-password` rotates it.

export const DESIGNER_ADMIN_EMAIL = 'designer@blog0.local';
export const DESIGNER_ADMIN_NAME = 'Designer';
export const DESIGNER_ADMIN_FILE = path.join('var', 'designer-admin.txt');

export type DesignerAdminStatus = 'created' | 'exists' | 'password_reset';

export interface DesignerAdminResult {
  status: DesignerAdminStatus;
  userId: string;
  email: string;
  /** Only set when a password was generated by this call (print it once, never log it). */
  password: string | null;
  file: string;
  fileExists: boolean;
}

/** 24 characters of base64url (144 bits) — passes the ≥ 12 character policy. */
export function generateDesignerPassword(): string {
  return randomBytes(18).toString('base64url');
}

function writeCredentials(file: string, email: string, password: string): void {
  mkdirSync(path.dirname(file), { recursive: true });
  const body =
    `# blog0 designer admin — generated by pnpm dev:design (sign in at /admin/login).\n` +
    `# Rotate: pnpm dev:design --reset-designer-password · Start over: rm -rf var/pglite var/storage var/pglite-session-secret var/designer-admin.txt\n` +
    `email: ${email}\n` +
    `password: ${password}\n`;
  writeFileSync(file, body, { mode: 0o600 });
  chmodSync(file, 0o600);
}

export async function ensureDesignerAdmin(
  db: Db,
  siteId: string,
  options: { resetPassword?: boolean; file?: string } = {},
): Promise<DesignerAdminResult> {
  const file = options.file ?? path.resolve(process.cwd(), DESIGNER_ADMIN_FILE);
  const existing = await findUserByEmail(siteId, DESIGNER_ADMIN_EMAIL, db);
  if (existing && !options.resetPassword) {
    return { status: 'exists', userId: existing.id, email: existing.email, password: null, file, fileExists: existsSync(file) };
  }
  const password = generateDesignerPassword();
  const result = await seedAdmin(
    db,
    siteId,
    { email: DESIGNER_ADMIN_EMAIL, password, displayName: DESIGNER_ADMIN_NAME },
    { resetPassword: options.resetPassword === true },
  );
  if (result.status === 'ok') {
    // Lost a race with a concurrent run that created it first: its password is the valid one.
    return { status: 'exists', userId: result.userId, email: result.email, password: null, file, fileExists: existsSync(file) };
  }
  writeCredentials(file, result.email, password);
  return {
    status: result.status === 'created' ? 'created' : 'password_reset',
    userId: result.userId,
    email: result.email,
    password,
    file,
    fileExists: true,
  };
}
