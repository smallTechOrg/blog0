/**
 * Where the designer credentials are kept: var/designer-admin.txt for the default ./var/pglite;
 * `<dir>.designer-admin.txt` for any other data dir, so a second PGlite dir (e.g. the E2E one)
 * never overwrites the designer's real credentials.
 */
export function designerAdminFileFor(dir: string): string {
  const normalized = path.normalize(dir).replace(/(.)[\\/]+$/, '$1');
  if (normalized === path.normalize(DEFAULT_PGLITE_DIR)) return DESIGNER_ADMIN_FILE;
  return `${normalized}.designer-admin.txt`;
}

// `pnpm dev:design` steps 1–6 (capability designer-mode; spec/roadmap.md → designer one-liner):
// ensure the PGlite dir → migrate → seed site + designer admin (+ BLOG0_ADMIN_* when set) → seed
// the 5 posts → seed decks (fixture when no key) → seed the sample recording → close PGlite. Idempotent: a second
// run creates nothing and prints no password. Uses the app's own handle (getDb()) so the seeders
// and any service they call share ONE PGlite instance (two instances on one dir can corrupt it).

export interface DesignerSetupOptions {
  resetDesignerPassword?: boolean;
  print?: (line: string) => void;
}

export interface DesignerSetupResult {
  dataDir: string;
  migrationsApplied: string[];
  postsCreated: number;
  decksSeeded: number;
  listen: SampleListenStatus;
  /** For the banner: `password` is set only when it was generated by this run (print it once). */
  admin: { email: string; password: string | null; status: DesignerAdminStatus; file: string; fileExists: boolean };
}

export async function runDesignerSetup(options: DesignerSetupOptions = {}): Promise<DesignerSetupResult> {
  const print = options.print ?? ((line: string) => void process.stdout.write(`${line}\n`));
  const config = getConfig();
  if (config.database.engine !== 'pglite') {
    throw new Error('dev:design runs on embedded PGlite only — BLOG0_DATABASE_URL must be pglite://<dir> or unset.');
  }
  const target = config.database;
  const dataDir = isMemoryPglite(target) ? 'memory' : resolvePgliteDir(target.dir);
  const fresh = !isMemoryPglite(target) && !existsSync(path.join(dataDir, 'PG_VERSION'));
  print(`database: ${describeDatabase(target)} (${fresh ? 'new — first boot runs initdb' : 'existing'})`);

  try {
    // 1–2. Open (creates the dir on first use) and migrate.
    const handle = await initDb();
    const applied = await runMigrations(handle);
    const status = await getMigrationStatus(handle);
    print(
      applied.length > 0
        ? `migrations: applied ${applied.join(', ')}`
        : `migrations: up to date (latest ${status.latestApplied ?? 'none'})`,
    );
    const { db } = handle;

    // 3. Site + designer admin (+ the .env admin when BLOG0_ADMIN_* are set).
    const siteResult = await seedSite(db, config.siteSlug);
    print(`site ${config.siteSlug}: ${siteResult.status === 'created' ? 'created' : 'ok'}`);
    const adminFile = designerAdminFileFor(target.dir);
    const admin = await ensureDesignerAdmin(db, siteResult.site.id, {
      resetPassword: options.resetDesignerPassword,
      file: path.resolve(process.cwd(), adminFile),
    });
    // The password itself is printed ONCE, in dev-design.mjs's banner after the server is up
    // (so it is the last thing on screen, not scrolled away by the dev server's output).
    if (admin.password !== null) {
      print(`admin account ${admin.email}: ${admin.status === 'created' ? 'created' : 'password rotated'} (password in the banner below; kept in ${adminFile})`);
    } else if (admin.fileExists) {
      print(`admin account ${admin.email}: ok (password in ${adminFile})`);
    } else {
      print(`admin account ${admin.email}: ok, but ${adminFile} is missing — rotate with: pnpm dev:design --reset-designer-password`);
    }
    if ((process.env.BLOG0_ADMIN_EMAIL ?? '').trim() !== '' && (process.env.BLOG0_ADMIN_PASSWORD ?? '').trim() !== '') {
      try {
        const envAdmin = await seedAdmin(db, siteResult.site.id, adminCredentialsFromEnv(process.env));
        print(`admin ${maskEmail(envAdmin.email)} (BLOG0_ADMIN_*): ${envAdmin.status === 'created' ? 'created' : 'ok'}`);
      } catch (error) {
        if (!(error instanceof SeedError)) throw error;
        print(`admin from BLOG0_ADMIN_* skipped: ${error.message}`);
      }
    }

    // 4. The 5 design articles, authored by the site's first admin.
    const authorId = (await firstAdminId(db, siteResult.site.id)) ?? admin.userId;
    const posts = await seedPosts(db, siteResult.site.id, authorId);
    print(`${SEED_POSTS.length} posts: ${posts.created.length} created`);

    // 5. Decks (fixture when no key).
    const decks = await seedTldr(db, siteResult.site.id, authorId, { source: 'auto' });
    print(formatSeedTldrSummary(decks));

    // 6. The sample recording, so Listen is visible (designer mode only).
    const listen = await seedSampleListen(db, siteResult.site.id, authorId);
    print(formatSampleListenSummary(listen));

    return {
      dataDir,
      migrationsApplied: applied,
      postsCreated: posts.created.length,
      decksSeeded: decks.seeded.length,
      listen: listen.status,
      admin: { email: admin.email, password: admin.password, status: admin.status, file: adminFile, fileExists: admin.fileExists },
    };
  } finally {
    // 7. Close PGlite before the dev server opens the same directory (single opener per dir).
    await closeDb();
  }
}

// ---------------------------------------------------------------------------------------------
// The designer's sample recording (designer mode ONLY — never the Postgres seeds): so Listen is
// visible without recording anything, ONE published recording — tests/fixtures/audio/sample.mp3
// (21 s) — is attached to SAMPLE_LISTEN_SLUG through the normal paths: uploadAudio() (probe →
// getStorage().put() into BLOG0_STORAGE_DIR, default ./var/storage → media_asset + listen draft)
// then publishArticle() (estimated timing: no stored marks). Idempotent: an article that already
// has a Listen row (seeded, uploaded or removed by the designer) is never touched — except that a
// seeded sample whose file vanished from the storage dir (e.g. `rm -rf var/storage` alone) is
// written back under the same key, so the player never points at a missing file.
// ---------------------------------------------------------------------------------------------

export const SAMPLE_LISTEN_SLUG = 'humans-are-software';
export const SAMPLE_LISTEN_FILE = path.join('tests', 'fixtures', 'audio', 'sample.mp3');

export type SampleListenStatus = 'seeded' | 'exists' | 'restored' | 'skipped';

export interface SampleListenResult {
  status: SampleListenStatus;
  slug: string;
  /** Why it was skipped (status 'skipped'). */
  reason?: string;
  /** Readers' timing for the published recording ('estimated' for the seeded sample). */
  timing?: string | null;
}

/** "listen: …" — the line `pnpm dev:design` prints. */
export function formatSampleListenSummary(result: SampleListenResult): string {
  switch (result.status) {
    case 'seeded':
      return `listen: sample recording seeded on ${result.slug} (${result.timing ?? 'estimated'} timing)`;
    case 'restored':
      return `listen: sample recording file restored for ${result.slug}`;
    case 'exists':
      return `listen: ${result.slug} already has a recording`;
    default:
      return `listen: sample recording skipped — ${result.reason}`;
  }
}

async function loadActor(db: Db, siteId: string, userId: string): Promise<ActorContext | null> {
  const [user] = await db
    .select({ id: appUser.id, siteId: appUser.siteId, email: appUser.email, displayName: appUser.displayName })
    .from(appUser)
    .where(and(eq(appUser.id, userId), eq(appUser.siteId, siteId), isNull(appUser.disabledAt)))
    .limit(1);
  return user ? { siteId, user } : null;
}

/**
 * Seeds the sample recording on SAMPLE_LISTEN_SLUG as `userId` (an admin of the site). `db` must
 * be the app's handle (getDb()). Never throws for a missing fixture/article — returns 'skipped'.
 */
export async function seedSampleListen(
  db: Db,
  siteId: string,
  userId: string,
  options: { file?: string; slug?: string } = {},
): Promise<SampleListenResult> {
  const slug = options.slug ?? SAMPLE_LISTEN_SLUG;
  const file = options.file ?? path.resolve(process.cwd(), SAMPLE_LISTEN_FILE);
  const skipped = (reason: string): SampleListenResult => ({ status: 'skipped', slug, reason });

  const [row] = await db
    .select({ id: article.id, status: article.status, currentRevisionId: article.currentRevisionId, publishedRevisionId: article.publishedRevisionId })
    .from(article)
    .where(and(eq(article.siteId, siteId), eq(article.slug, slug)))
    .limit(1);
  if (!row) return skipped(`${slug} is not in this site`);
  if (!existsSync(file)) return skipped(`${path.relative(process.cwd(), file) || file} is missing`);

  const existing = await findFormatRow(siteId, row.id, 'listen', db);
  if (existing) {
    // Self-heal only our own sample: same bytes (sha256) as the fixture, file gone from storage.
    const published = readListenPayload(existing.publishedPayload);
    if (published && (await getStorage().stat(published.audio.key)) === null) {
      const asset = await findMediaAssetByKey(siteId, published.audio.key, db);
      const buffer = readFileSync(file);
      if (asset && asset.sha256 === createHash('sha256').update(buffer).digest('hex')) {
        await getStorage().put(published.audio.key, buffer, { maxBytes: buffer.length });
        return { status: 'restored', slug };
      }
    }
    return { status: 'exists', slug };
  }
  if (row.status !== 'published' || row.currentRevisionId === null || row.currentRevisionId !== row.publishedRevisionId) {
    // Publishing here would also publish a writer's unpublished edits — leave it alone.
    return skipped(`${slug} is unpublished or has unpublished changes`);
  }
  const actor = await loadActor(db, siteId, userId);
  if (!actor) return skipped(`user ${userId} is not an active admin of this site`);

  const buffer = readFileSync(file);
  await uploadAudio(row.id, new File([new Uint8Array(buffer)], 'sample.mp3', { type: 'audio/mpeg' }), actor);
  await publishArticle(actor, row.id, row.currentRevisionId);
  const state = await getListenState(siteId, row.id);
  return { status: 'seeded', slug, timing: state.timing };
}
