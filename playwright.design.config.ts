import { defineConfig, devices } from '@playwright/test';

import {
  DESIGN_E2E_ADMIN_FILE,
  DESIGN_E2E_DIR,
  DESIGN_E2E_PORT,
  DESIGN_E2E_SERVER_LOG,
} from './tests/e2e/designer.global-setup';

// Designer-mode E2E (capability designer-mode): the app exactly as a designer runs it —
// `pnpm dev:design` (embedded PGlite + the hot-reload dev server), from a clean state, with no
// Postgres and no `.env` values for the database, the session secret or the OpenRouter key.
//
//   - own port 3413 and own PGlite dir ./var/pglite-e2e (credentials: var/pglite-e2e.designer-admin.txt),
//     so a designer's ./var/pglite and the main E2E (3411, blog0_test) are never touched;
//   - Playwright starts the web server BEFORE globalSetup, so the clean-state wipe of var/pglite-e2e*
//     is the first step of the web server command itself; globalSetup then checks that the boot really
//     was a first boot and hands the generated designer credentials to the tests;
//   - BLOG0_SESSION_SECRET / BLOG0_OPENROUTER_API_KEY / BLOG0_ADMIN_* / BLOG0_LOG_FILE are set EMPTY:
//     an already-set variable is never overridden by .env (@next/env), and the app treats an empty
//     value as absent — so .env cannot fill them;
//   - the server's console (incl. the once-printed designer password for this throwaway DB) goes to
//     test-results/design-e2e-server.log (gitignored), never to the test output.
//
// This config deliberately does NOT load .env. Run: pnpm test:e2e:design

const baseURL = `http://localhost:${DESIGN_E2E_PORT}`;

// Clean-clone state for this data dir only (the shared session-secret file is regenerated by Gate 2's
// own `rm -rf`; wiping it here would sign a designer out of their running ./var/pglite site).
const wipe =
  `node -e "const fs=require('node:fs');` +
  `for (const p of ['${DESIGN_E2E_DIR}','${DESIGN_E2E_ADMIN_FILE}']) fs.rmSync(p,{recursive:true,force:true});` +
  `fs.mkdirSync('test-results',{recursive:true})"`;

export default defineConfig({
  testDir: 'tests/e2e',
  testMatch: 'designer-mode.spec.ts',
  globalSetup: './tests/e2e/designer.global-setup.ts',
  outputDir: 'test-results/playwright-design',
  fullyParallel: false,
  workers: 1,
  retries: 0,
  forbidOnly: process.env.CI === 'true',
  reporter: [['list'], ['html', { open: 'never', outputFolder: 'test-results/design-report' }]],
  timeout: 90_000,
  expect: { timeout: 15_000 },
  use: {
    baseURL,
    trace: 'retain-on-failure',
  },
  projects: [{ name: 'designer', use: { ...devices['Desktop Chrome'] } }],
  webServer: {
    command: `${wipe} && pnpm dev:design > ${DESIGN_E2E_SERVER_LOG} 2>&1`,
    url: `${baseURL}/api/health`,
    env: {
      BLOG0_PORT: String(DESIGN_E2E_PORT),
      BLOG0_DATABASE_URL: `pglite://./${DESIGN_E2E_DIR}`,
      BLOG0_PUBLIC_BASE_URL: baseURL,
      BLOG0_SESSION_SECRET: '',
      BLOG0_OPENROUTER_API_KEY: '',
      BLOG0_ADMIN_EMAIL: '',
      BLOG0_ADMIN_PASSWORD: '',
      BLOG0_ADMIN_NAME: '',
      BLOG0_LOG_FILE: '',
    },
    reuseExistingServer: false,
    timeout: 240_000,
    stdout: 'ignore',
    stderr: 'pipe',
  },
});
